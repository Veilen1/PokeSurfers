# Extracts the Latin glyphs from the Pokemon Emerald font reference sheet
# (assets/Sprites-Emerald/font.gif, ripped by Jackster on The Spriters Resource)
# into a compact alpha atlas plus metrics for the in-game HUD.
#
# Run from the repository root: powershell -ExecutionPolicy Bypass -File scripts/extract-emerald-font.ps1

Add-Type -AssemblyName System.Drawing

$root = Split-Path -Parent $PSScriptRoot
$sourcePath = Join-Path $root "assets\Sprites-Emerald\font.gif"
$atlasPath = Join-Path $root "frontend\public\game\ui\font-emerald.png"
$dataPath = Join-Path $root "frontend\src\pixelFontData.ts"

if (-not (Test-Path $sourcePath)) {
  throw "Font sheet not found at $sourcePath"
}

$source = [System.Drawing.Bitmap]::FromFile($sourcePath)

# Each band is one 8px text row on the reference sheet. The x scan keeps the
# glyph cores and ignores the pale drop shadow that would merge letters.
$bands = @(
  @{ chars = '0123456789!?.-,'; top = 117; height = 8 },
  @{ chars = 'ABCDEFGHIJKLMNOP'; top = 143; height = 8 },
  @{ chars = 'QRSTUVWXYZ'; top = 157; height = 8 }
)

$glyphs = New-Object System.Collections.Generic.List[object]

foreach ($band in $bands) {
  $runs = New-Object System.Collections.Generic.List[object]
  $inRun = $false
  $runStart = 0
  for ($x = 20; $x -lt 190; $x++) {
    $dark = 0
    for ($y = $band.top; $y -lt ($band.top + $band.height); $y++) {
      $pixel = $source.GetPixel($x, $y)
      if (($pixel.R + $pixel.G + $pixel.B) -lt 420) { $dark++ }
    }
    if ($dark -gt 0 -and -not $inRun) {
      $inRun = $true
      $runStart = $x
    } elseif ($dark -eq 0 -and $inRun) {
      $inRun = $false
      $runs.Add(@($runStart, ($x - 1)))
    }
  }
  if ($inRun) { $runs.Add(@($runStart, 189)) }

  if ($runs.Count -ne $band.chars.Length) {
    throw "Band at y=$($band.top) produced $($runs.Count) runs for $($band.chars.Length) characters."
  }

  for ($index = 0; $index -lt $runs.Count; $index++) {
    $left = $runs[$index][0]
    $right = $runs[$index][1]
    $glyphs.Add([pscustomobject]@{
      char = [string]$band.chars[$index]
      x = $left
      y = $band.top
      w = ($right - $left + 1)
      h = $band.height
    })
  }
}

# Pack the masks into a padded atlas.
$padding = 2
$maxWidth = 256
$cursorX = $padding
$cursorY = $padding
$rowHeight = 8
$positions = @{}
foreach ($glyph in $glyphs) {
  if ($cursorX + $glyph.w + $padding -gt $maxWidth) {
    $cursorX = $padding
    $cursorY += $rowHeight + $padding
  }
  $positions[$glyph.char] = [pscustomobject]@{ x = $cursorX; y = $cursorY; w = $glyph.w }
  $cursorX += $glyph.w + $padding
}
$atlasWidth = $maxWidth
$atlasHeight = $cursorY + $rowHeight + $padding

$atlas = New-Object System.Drawing.Bitmap -ArgumentList $atlasWidth, $atlasHeight, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)

# Turn the grey reference glyphs into a white alpha mask. The pale drop shadow
# becomes partial alpha, which keeps the soft GBA edge when the mask is tinted.
foreach ($glyph in $glyphs) {
  $position = $positions[$glyph.char]
  for ($y = 0; $y -lt $glyph.h; $y++) {
    for ($x = 0; $x -lt $glyph.w; $x++) {
      $pixel = $source.GetPixel($glyph.x + $x, $glyph.y + $y)
      $luminance = ($pixel.R + $pixel.G + $pixel.B) / 3.0
      if ($luminance -lt 150) {
        $alpha = 255
      } elseif ($luminance -lt 215) {
        $alpha = 100
      } else {
        $alpha = 0
      }
      if ($alpha -le 4) { continue }
      $atlas.SetPixel(($position.x + $x), ($position.y + $y), [System.Drawing.Color]::FromArgb($alpha, 255, 255, 255))
    }
  }
}

$atlas.Save($atlasPath, [System.Drawing.Imaging.ImageFormat]::Png)
$atlas.Dispose()
$source.Dispose()

$glyphJson = ($positions.Keys | Sort-Object | ForEach-Object {
  $entry = $positions[$_]
  $escaped = $_ -replace '\\', '\\\\' -replace '"', '\"'
  "    `"$escaped`": { x: $($entry.x), y: $($entry.y), w: $($entry.w) },"
}) -join "`n"

$contents = @"
// Generated by scripts/extract-emerald-font.ps1 from the Pokemon Emerald font
// sheet (assets/Sprites-Emerald/font.gif, ripped by Jackster).
export interface PixelGlyph {
  x: number
  y: number
  w: number
}

export const PIXEL_FONT = {
  atlas: { width: $atlasWidth, height: $atlasHeight },
  lineHeight: $rowHeight,
  spacing: 1,
  spaceWidth: 3,
  glyphs: {
$glyphJson
  } as Record<string, PixelGlyph>,
}
"@

[System.IO.File]::WriteAllText($dataPath, $contents, (New-Object System.Text.UTF8Encoding($false)))

Write-Output "Wrote $atlasPath (${atlasWidth}x${atlasHeight}) and $dataPath with $($glyphs.Count) glyphs."
