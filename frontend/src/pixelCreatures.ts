const motifAccents: Record<string, string> = {
  ember: '#ffe49a',
  tide: '#f5ffff',
  star: '#fff2a8',
  mushroom: '#ffe9f3',
  cloud: '#ffffff',
}

export function drawPixelCreature(
  context: CanvasRenderingContext2D,
  creature: Creature,
  centerX: number,
  centerY: number,
  size: number,
): void {
  const rows = sprites[creature.motif] ?? sprites.leaf
  const gridSize = 20
  const pixel = size / gridSize
  const colors: Record<string, string> = {
    '#': creature.palette.dark,
    '@': creature.palette.body,
    '+': creature.palette.light,
    '*': motifAccents[creature.motif] ?? creature.palette.light,
    o: '#fff8e9',
    x: '#182b2c',
  }

  context.save()
  context.imageSmoothingEnabled = false
  context.fillStyle = 'rgba(0, 0, 0, .28)'
  context.fillRect(centerX - size * 0.3, centerY + size * 0.35, size * 0.6, pixel * 2)

  rows.forEach((row, rowIndex) => {
    const startX = Math.floor((gridSize - row.length) / 2)
    for (let column = 0; column < row.length; column += 1) {
      const color = colors[row[column]]
      if (!color) continue
      context.fillStyle = color
      context.fillRect(
        centerX - size / 2 + (startX + column) * pixel,
        centerY - size / 2 + rowIndex * pixel,
        pixel,
        pixel,
      )
    }
  })

  context.restore()
}
